// Recurring tasks must keep the existing scheduling logic — the one-off branch
// must not steal their StartDate.
func TestGetNextTaskDate_RecurringUnaffected(t *testing.T) {
	st := &ScheduleTask{
		Repeating:       true,
		RepeatFrequency: ScheduleTaskRepeatFrequencyDaily,
		StartDate:       date(2026, 8, 15),
	}

	got, err := getNextTaskDate(st)
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	// Daily recurring resolves relative to now, never to the far StartDate.
	if got.Year() == 2026 && got.Month() == time.August && got.Day() == 15 {
		t.Fatal("recurring task must not materialize on its StartDate")
	}
}

// A one-off with frequency "custom" must NOT be regenerated by the lazy day
// generator, so it never duplicates on the selected date nor leaks onto today.
func TestShouldCreateTaskForToday_OneOffCustomNotRegenerated(t *testing.T) {
	st := &ScheduleTask{
		Repeating: false,
		Frequency: ScheduleTaskFrequencyCustom,
		StartDate: date(2026, 8, 15),
	}
	if shouldCreateTaskForToday(st, date(2026, 8, 15)) {
		t.Fatal("custom one-off must not be regenerated by lazy day generation")
	}
	if shouldCreateTaskForToday(st, date(2026, 8, 16)) {
		t.Fatal("custom one-off must not appear on other days")
	}
}
